/** 按关键词模糊找课（归一化后包含匹配，忽略空格与中文标点差异） */
export function findLessonsByTitle(query: string): XioshiLesson[] {
  const q = normalizeTitle(query.trim().toLowerCase())
  if (!q) return []
  return xiaoshiLessons.filter(l => normalizeTitle(l.title.toLowerCase()).includes(q))
}

/** 某一层的全部课程（X 类恒为空） */
export function lessonsOfLayer(layerId: string): XioshiLesson[] {
  return xiaoshiLessons.filter(l => l.layerId === layerId)
}

/** 课程总数（不含生活互动） */
export const xiaoshiLessonCount = xiaoshiLessons.filter(l => l.layerId !== null).length
