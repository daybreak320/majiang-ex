/** 主题簇代码：教学 8 簇 + X（生活互动，不入课表） */
export type ClusterCode = 'E' | 'D' | 'I' | 'P' | 'T' | 'S' | 'G' | 'M' | 'X'

export interface XioshiClusterMeta {
  code: ClusterCode
  name: string
  summary: string
  /** 该簇全部期数标题（已去重、剔除话题标签） */
  titles: string[]
  /** 建议精读的期数标题（归一化匹配口径的子集） */
  mustRead: string[]
}

export interface PathLayer {
  id: string
  name: string
  /** 建议学习节奏 */
  weeks: string
  goal: string
  clusters: ClusterCode[]
}

export interface XioshiLesson {
  title: string
  cluster: ClusterCode
  /** 建议精读 */
  mustRead: boolean
  layerId: string | null
}

/** 归一化标题：去空格与常见中文标点（与 feed 清洗口径一致，供模糊匹配） */
export function normalizeTitle(s: string): string {
  return s.replace(/[，。！？、…—\s·]+/g, '')
}

